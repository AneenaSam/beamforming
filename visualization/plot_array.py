#!/usr/bin/env python3
"""
Phase 1 Visualization: 36-Sensor Uniform Circular Array Geometry
Reads sensor coordinates from data/sensor_positions.csv generated by the C++ engine
and renders a dual-pane dark-theme scientific visualization (Cartesian and Polar).
"""

import os
import sys
import numpy as np
import matplotlib
# Use Agg if DISPLAY/GUI is not connected, but allow showing if interactive
if not os.environ.get("DISPLAY") and sys.platform != "win32":
    matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as patches

def load_sensor_data(csv_path="data/sensor_positions.csv"):
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Sensor CSV file not found: {csv_path}. Please run beamforming_app first.")
    
    metadata = {}
    rows = []
    import csv
    with open(csv_path, "r") as f:
        reader = csv.reader(f)
        for line in reader:
            if not line:
                continue
            first = line[0].strip()
            if first.startswith("#"):
                clean = first.strip("# ")
                if "=" in clean:
                    k, v = clean.split("=", 1)
                    metadata[k.strip()] = float(v.strip())
            elif first == "sensor_id":
                header = line
            else:
                rows.append([float(x) for x in line])
                
    arr = np.array(rows)
    data = {
        "sensor_id": arr[:, 0].astype(int),
        "angle_rad": arr[:, 1],
        "angle_deg": arr[:, 2],
        "x_m": arr[:, 3],
        "y_m": arr[:, 4]
    }
    return metadata, data

def plot_circular_array(csv_path="data/sensor_positions.csv", save_path="docs/phase1_circular_array.png"):
    metadata, data = load_sensor_data(csv_path)
    
    num_sensors = int(metadata.get("NumSensors", len(data)))
    freq_hz = metadata.get("FrequencyHz", 1000.0)
    c = metadata.get("SpeedOfSoundMps", 343.0)
    wavelength = metadata.get("WavelengthM", c / freq_hz)
    radius = metadata.get("RadiusM", 1.5 * wavelength)
    arc_dist = metadata.get("InterElementArcDistM", radius * (2 * np.pi / num_sensors))
    
    # Configure Dark Scientific Theme
    plt.style.use("dark_background")
    fig = plt.figure(figsize=(15, 7.5), facecolor="#0e1117")
    
    # ==========================
    # LEFT PANEL: Cartesian Plot
    # ==========================
    ax_cart = fig.add_subplot(1, 2, 1)
    ax_cart.set_facecolor("#161b22")
    
    # Boundary circle
    circle = patches.Circle((0, 0), radius, edgecolor="#388bfd", facecolor="#1f6feb",
                            alpha=0.08, linewidth=2, linestyle="--", label="Array Boundary")
    ax_cart.add_patch(circle)
    
    # Array Center
    ax_cart.plot(0, 0, marker="+", markersize=14, color="#f85149", markeredgewidth=2.5, label="Array Center (0, 0)")
    
    # Radius vector arrow
    ax_cart.annotate("", xy=(radius, 0), xytext=(0, 0),
                     arrowprops=dict(arrowstyle="->", color="#3fb950", lw=2, mutation_scale=15))
    ax_cart.text(radius * 0.45, 0.035, f"R = {radius:.4f} m\n(1.5 λ)",
                 color="#3fb950", fontsize=10, fontweight="bold", ha="center")
    
    # Plot Sensors
    xs = data["x_m"]
    ys = data["y_m"]
    ids = data["sensor_id"].astype(int)
    angles_deg = data["angle_deg"]
    
    # Scatter plot with glowing markers
    ax_cart.scatter(xs, ys, color="#58a6ff", s=90, edgecolor="#ffffff", linewidth=1.2, zorder=5, label="Sensors (M=36)")
    
    # Label each sensor with slight radial offset
    label_radius = radius * 1.15
    for i in range(num_sensors):
        rad = np.radians(angles_deg[i])
        lx = label_radius * np.cos(rad)
        ly = label_radius * np.sin(rad)
        ax_cart.text(lx, ly, f"{ids[i]}", color="#f0f6fc", fontsize=8.5, ha="center", va="center",
                     bbox=dict(boxstyle="circle,pad=0.2", facecolor="#21262d", edgecolor="#30363d", alpha=0.9))
    
    # Axes styling
    margin = radius * 1.35
    ax_cart.set_xlim(-margin, margin)
    ax_cart.set_ylim(-margin, margin)
    ax_cart.set_aspect("equal")
    ax_cart.grid(True, linestyle=":", alpha=0.35, color="#8b949e")
    ax_cart.set_xlabel("X Position (meters)", color="#c9d1d9", fontsize=11, fontweight="bold")
    ax_cart.set_ylabel("Y Position (meters)", color="#c9d1d9", fontsize=11, fontweight="bold")
    ax_cart.set_title("Uniform Circular Array (Cartesian Coordinates)", color="#58a6ff", fontsize=13, fontweight="bold", pad=12)
    ax_cart.legend(loc="upper left", facecolor="#21262d", edgecolor="#30363d", fontsize=9)
    
    # ==========================
    # RIGHT PANEL: Polar Plot
    # ==========================
    ax_polar = fig.add_subplot(1, 2, 2, projection="polar")
    ax_polar.set_facecolor("#161b22")
    
    # Polar plot sensor points
    thetas = data["angle_rad"]
    radii = np.full_like(thetas, radius)
    ax_polar.scatter(thetas, radii, color="#58a6ff", s=100, edgecolor="#ffffff", linewidth=1.2, zorder=5)
    
    # Connect circumference ring
    theta_dense = np.linspace(0, 2 * np.pi, 360)
    ax_polar.plot(theta_dense, np.full_like(theta_dense, radius), color="#388bfd", linestyle="--", linewidth=1.5, alpha=0.7)
    
    # Cardinal direction markers
    ax_polar.set_theta_zero_location("E")  # 0 deg along +X axis
    ax_polar.set_theta_direction(1)        # Counterclockwise
    ax_polar.set_rlim(0, radius * 1.3)
    ax_polar.grid(True, linestyle=":", alpha=0.4, color="#8b949e")
    ax_polar.tick_params(colors="#c9d1d9")
    ax_polar.set_title("Angular Distribution (Polar View: 0° to 360°)", color="#58a6ff", fontsize=13, fontweight="bold", pad=12)
    
    # Angular labels for cardinal points
    cardinal_angles = [0, 90, 180, 270]
    for ca in cardinal_angles:
        rad = np.radians(ca)
        ax_polar.plot([rad, rad], [0, radius], color="#8b949e", linestyle=":", lw=1)
        
    # Technical Metadata Box
    param_text = (
        f"Array Specifications:\n"
        f"• Number of Sensors (M): {num_sensors}\n"
        f"• Angular Spacing (Δθ): 10.0° (2π/36 rad)\n"
        f"• Acoustic Speed (c): {c:.1f} m/s\n"
        f"• Signal Frequency (f): {freq_hz:.1f} Hz\n"
        f"• Acoustic Wavelength (λ): {wavelength:.4f} m ({wavelength*100:.1f} cm)\n"
        f"• Array Radius (R): {radius:.4f} m (1.5 λ)\n"
        f"• Inter-Sensor Arc (d): {arc_dist:.4f} m ({arc_dist/wavelength:.4f} λ)\n"
        f"• Spatial Nyquist: d < λ/2 (0.2618 λ < 0.5 λ) -> No Aliasing"
    )
    fig.text(0.5, 0.02, param_text, ha="center", fontsize=9.5, family="monospace", color="#e6edf3",
             bbox=dict(boxstyle="round,pad=0.6", facecolor="#21262d", edgecolor="#388bfd", alpha=0.95))
    
    plt.tight_layout(rect=[0, 0.12, 1, 0.98])
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    plt.savefig(save_path, dpi=300, facecolor=fig.get_facecolor(), bbox_inches="tight")
    print(f"[INFO] High-resolution visualization saved to: {save_path}")
    
    # Display plot if interactive environment allows
    try:
        if os.environ.get("DISPLAY") or sys.platform == "win32":
            plt.show(block=False)
            plt.pause(1.0)
    except Exception:
        pass
    plt.close()

if __name__ == "__main__":
    plot_circular_array()
